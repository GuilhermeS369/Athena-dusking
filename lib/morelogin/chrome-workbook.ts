export function buildMoreLoginChromeRows(profiles: MoreLoginChromeProfile[], proxyType: MoreLoginProxyType, groupName = '') {
  const group = groupName.trim();
  return [
    [MORELOGIN_CHROME_INSTRUCTIONS],
    MORELOGIN_CHROME_HEADERS,
    MORELOGIN_CHROME_DESCRIPTIONS,
    ...profiles.map((profile) => [
      profile.profileName,
      MORELOGIN_CHROME_PLATFORM,
      MORELOGIN_CHROME_PLATFORM_DOMAIN,
      profile.login,
      profile.password,
      profile.twoFa,
      '',
      profile.proxy ? proxyType : '',
      profile.proxy ?? '',
      '',
      '',
      group,
      '',
      '',
      '',
      '',
    ]),
  ];
}

function escapeXml(value: string) {
  return value
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&apos;');
}

function columnName(index: number) {
  let name = '';
  for (let cursor = index + 1; cursor > 0; cursor = Math.floor((cursor - 1) / 26)) {
    name = String.fromCharCode(65 + ((cursor - 1) % 26)) + name;
  }
  return name;
}

const XML_DECLARATION = '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>';

export function buildMoreLoginChromeSheetXml(rows: string[][]) {
  const body = rows.map((row, rowIndex) => {
    const rowNumber = rowIndex + 1;
    // Célula vazia fica fora do XML, como no modelo aceito.
    const cells = row
      .map((value, columnIndex) => (value
        ? `<c r="${columnName(columnIndex)}${rowNumber}" t="inlineStr"><is><t xml:space="preserve">${escapeXml(value)}</t></is></c>`
        : ''))
      .join('');
    return `<row r="${rowNumber}">${cells}</row>`;
  }).join('');
  return `${XML_DECLARATION}<worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main"><sheetData>${body}</sheetData></worksheet>`;
}

// Caminho dentro do .xlsx -> conteúdo. Quem chama só precisa zipar.
export function buildMoreLoginChromePackage(rows: string[][]): Record<string, string> {
  return {
    '[Content_Types].xml': `${XML_DECLARATION}<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types"><Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/><Default Extension="xml" ContentType="application/xml"/><Override PartName="/xl/workbook.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.sheet.main+xml"/><Override PartName="/xl/worksheets/sheet1.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.worksheet+xml"/></Types>`,
    '_rels/.rels': `${XML_DECLARATION}<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships"><Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" Target="xl/workbook.xml"/></Relationships>`,
    'xl/workbook.xml': `${XML_DECLARATION}<workbook xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main" xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships"><sheets><sheet name="Sheet1" sheetId="1" r:id="rId1"/></sheets></workbook>`,
    'xl/_rels/workbook.xml.rels': `${XML_DECLARATION}<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships"><Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/worksheet" Target="worksheets/sheet1.xml"/></Relationships>`,
    'xl/worksheets/sheet1.xml': buildMoreLoginChromeSheetXml(rows),
  };
}
